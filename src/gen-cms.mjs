// Generates .pages.yml (Pages CMS configuration) from the structure of content/en.json.
// Run after adding new keys to the content files: `node src/gen-cms.mjs`.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const en = JSON.parse(fs.readFileSync(path.join(ROOT, 'content/en.json'), 'utf8'));

const SECTION_LABELS = {
  lang: 'Código de idioma (não alterar)', meta: 'SEO (título e descrição)', nav: 'Menu de navegação', hero: 'Topo da página (hero)',
  stats: 'Indicadores do topo', photoBand: 'Faixa de foto (pipetagem)', challenge: 'Ponto de partida', platform: 'Plataforma',
  viewer: 'Visualizador da molécula', dnaBand: 'Faixa de foto (ADN)', applications: 'Aplicações', biosensing: 'Biossensores',
  services: 'Serviços', team: 'Equipa', funding: 'Financiamento', contact: 'Contacto', form: 'Formulário de contacto',
  footer: 'Rodapé', widgets: 'WhatsApp e assistente', privacyPage: 'Política de Privacidade',
};

const q = (s) => JSON.stringify(s);
const isLong = (v) => typeof v === 'string' && (v.length > 90 || /<[a-z]/i.test(v));

function field(name, value, ind) {
  const pad = ' '.repeat(ind);
  const label = SECTION_LABELS[name] || name;
  let out = `${pad}- name: ${q(name)}\n${pad}  label: ${q(label)}\n`;
  if (Array.isArray(value)) {
    if (typeof value[0] === 'object') {
      const first = Object.keys(value[0])[0];
      out += `${pad}  type: object\n${pad}  list:\n${pad}    collapsible:\n${pad}      collapsed: true\n${pad}      summary: "{${first}}"\n${pad}  fields:\n`;
      for (const [k, v] of Object.entries(value[0])) out += field(k, v, ind + 4);
    } else {
      out += `${pad}  type: ${value.some(isLong) ? 'text' : 'string'}\n${pad}  list: true\n`;
    }
  } else if (value && typeof value === 'object') {
    out += `${pad}  type: object\n${pad}  fields:\n`;
    for (const [k, v] of Object.entries(value)) out += field(k, v, ind + 4);
  } else if (typeof value === 'boolean') {
    out += `${pad}  type: boolean\n`;
  } else {
    out += `${pad}  type: ${isLong(value) ? 'text' : 'string'}\n`;
    if (name === 'lang') out += `${pad}  readonly: true\n`;
  }
  return out;
}

function fileEntry(name, label, file) {
  let out = `  - name: ${name}\n    label: ${q(label)}\n    type: file\n    path: ${file}\n    format: json\n    fields:\n`;
  for (const [k, v] of Object.entries(en)) out += field(k, v, 6);
  return out;
}

const settings = JSON.parse(fs.readFileSync(path.join(ROOT, 'content/settings.json'), 'utf8'));
const SETTINGS_LABELS = {
  siteUrl: 'Endereço do site', companyName: 'Nome legal', nipc: 'NIPC', email: 'Email público',
  addressLine1: 'Morada (linha 1)', addressLine2: 'Morada (linha 2)', formEndpoint: 'Endereço Formspree do formulário',
  whatsappNumber: 'Número WhatsApp (com indicativo, ex. 351912345678; vazio esconde o botão)', showChatAssistant: 'Mostrar assistente de perguntas',
  mapQuery: 'Morada usada no mapa', cloudflareAnalyticsToken: 'Token Cloudflare Web Analytics', googleSiteVerification: 'Código de verificação Google',
};
let settingsYml = `  - name: settings\n    label: "Definições gerais (email, formulário, WhatsApp)"\n    type: file\n    path: content/settings.json\n    format: json\n    fields:\n`;
for (const [k, v] of Object.entries(settings)) {
  settingsYml += `      - name: ${q(k)}\n        label: ${q(SETTINGS_LABELS[k] || k)}\n        type: ${typeof v === 'boolean' ? 'boolean' : 'string'}\n`;
}

const yml = `# Pages CMS configuration (https://pagescms.org). Generated by src/gen-cms.mjs.
# Every save in Pages CMS creates a commit; GitHub Actions then rebuilds and publishes the site.
media:
  input: assets/img
  output: /assets/img
content:
${fileEntry('pt', 'Textos em português (PT)', 'content/pt.json')}${fileEntry('en', 'Textos em inglês (EN)', 'content/en.json')}${settingsYml}  - name: chatbot
    label: "Assistente: perguntas e respostas"
    type: file
    path: content/chatbot-kb.json
`;
fs.writeFileSync(path.join(ROOT, '.pages.yml'), yml);
console.log('Wrote .pages.yml');
